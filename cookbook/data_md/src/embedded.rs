use cookbook_core::{
    Plan, PlanError, PlanReader, PlanResult, Recipe, RecipeError, RecipeReader, RecipeResult,
};
use std::collections::HashMap;
use std::sync::OnceLock;
use uuid::Uuid;

/// Embedded recipe store that includes all recipe markdown files at compile time.
/// This is suitable for WASM/web targets where filesystem access is not available.
#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
///
/// Recipes are keyed by UUID, with an index from each recipe's legacy ID to its UUID, the same
/// way as [`crate::MarkdownRecipeStore`].
pub struct EmbeddedRecipeStore {
    recipes: HashMap<Uuid, Recipe>,
    ids: HashMap<String, Uuid>,
}

static EMBEDDED_STORE: OnceLock<EmbeddedRecipeStore> = OnceLock::new();

#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
impl EmbeddedRecipeStore {
    /// Get the global embedded recipe store instance
    pub fn global() -> &'static EmbeddedRecipeStore {
        EMBEDDED_STORE.get_or_init(|| {
            let mut store = EmbeddedRecipeStore {
                recipes: HashMap::new(),
                ids: HashMap::new(),
            };
            store.load_embedded_recipes();
            store
        })
    }

    /// Load all embedded recipes at initialization
    fn load_embedded_recipes(&mut self) {
        // Recipe files are auto-generated by build.rs at compile time
        // This prevents issues when files are added, removed, or renamed
        let recipe_files: Vec<(u32, &str)> =
            include!(concat!(env!("OUT_DIR"), "/embedded_recipes.rs"));

        for (day, content) in recipe_files {
            match Self::parse_recipe_markdown(content, day) {
                Ok(recipe) => {
                    if let Err(e) = self.insert(recipe) {
                        tracing::warn!(day = day, error = %e, "Skipped recipe for day {}", day);
                    }
                }
                Err(e) => {
                    // Log parsing failures to help with debugging
                    tracing::warn!(
                        day = day,
                        error = %e,
                        "Failed to parse recipe markdown for day {}",
                        day
                    );
                }
            }
        }

        // build.rs fails the build unless a recipe file exists for every day 1-365,
        // so a shortfall here can only come from a parse failure, logged above.
        if self.recipes.len() != 365 {
            tracing::error!(
                loaded = self.recipes.len(),
                "Expected to load 365 recipes but loaded {}",
                self.recipes.len()
            );
        }
    }

    /// Adds `recipe`, unless another recipe already has its UUID or legacy ID.
    fn insert(&mut self, recipe: Recipe) -> RecipeResult<()> {
        if self.recipes.contains_key(&recipe.uuid) || self.ids.contains_key(&recipe.id) {
            return Err(RecipeError::AlreadyExists(format!(
                "Recipe with id '{}' or uuid '{}' already exists",
                recipe.id, recipe.uuid
            )));
        }
        self.ids.insert(recipe.id.clone(), recipe.uuid);
        self.recipes.insert(recipe.uuid, recipe);
        Ok(())
    }

    /// The UUID of the recipe that `id` names: a UUID string or a legacy ID.
    fn resolve_id(&self, id: &str) -> Option<Uuid> {
        if let Ok(uuid) = Uuid::parse_str(id)
            && self.recipes.contains_key(&uuid)
        {
            return Some(uuid);
        }
        self.ids.get(id).copied()
    }

    /// Parses recipe data from markdown content
    fn parse_recipe_markdown(content: &str, day: u32) -> RecipeResult<Recipe> {
        crate::parse::recipe(
            content,
            format!("day-{}", day),
            format!("Day {} Recipe", day),
        )
    }
}

#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
impl RecipeReader for EmbeddedRecipeStore {
    /// Accepts a UUID string or a legacy ID such as `day-1`.
    fn get_by_id(&self, id: &str) -> RecipeResult<Recipe> {
        self.resolve_id(id)
            .and_then(|uuid| self.recipes.get(&uuid))
            .cloned()
            .ok_or_else(|| RecipeError::NotFound(format!("Recipe with id '{}' not found", id)))
    }

    fn get_by_uuid(&self, uuid: &Uuid) -> RecipeResult<Recipe> {
        self.recipes
            .get(uuid)
            .cloned()
            .ok_or_else(|| RecipeError::NotFound(format!("Recipe with uuid '{}' not found", uuid)))
    }

    #[allow(deprecated)]
    fn get_all(&self) -> RecipeResult<Vec<Recipe>> {
        Ok(self.recipes.values().cloned().collect())
    }

    /// Accepts a UUID string or a legacy ID, like [`RecipeReader::get_by_id`].
    fn exists(&self, id: &str) -> bool {
        self.resolve_id(id).is_some()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_embedded_store_loads_recipes() {
        let store = EmbeddedRecipeStore::global();
        let recipes = store.get_all().unwrap();
        assert_eq!(recipes.len(), 365, "Should load all 365 recipes");
    }

    #[test]
    fn test_recipe_has_content() {
        let store = EmbeddedRecipeStore::global();
        let recipe = store.get_by_id("day-1").unwrap();

        // Verify recipe has parsed content
        assert!(!recipe.title.is_empty());
        assert!(recipe.description.is_some());
        assert!(!recipe.ingredients.is_empty());
        assert!(!recipe.instructions.is_empty());
        assert!(recipe.prep_time_minutes.is_some());
        assert!(recipe.cook_time_minutes.is_some());
        assert!(recipe.servings.is_some());
    }

    #[test]
    fn test_recipe_found_by_uuid_and_legacy_id() {
        let store = EmbeddedRecipeStore::global();
        let recipe = store.get_by_id("day-1").unwrap();
        let uuid = recipe.uuid.to_string();

        assert!(store.exists("day-1"));
        assert!(store.exists(&uuid), "exists should accept a UUID");
        assert_eq!(store.get_by_id(&uuid).unwrap().id, "day-1");
        assert_eq!(store.get_by_uuid(&recipe.uuid).unwrap().id, "day-1");
    }

    #[test]
    fn test_every_recipe_found_by_uuid() {
        let store = EmbeddedRecipeStore::global();
        for recipe in store.get_all().unwrap() {
            assert!(store.exists(&recipe.uuid.to_string()));
            assert_eq!(store.get_by_uuid(&recipe.uuid).unwrap().id, recipe.id);
        }
    }

    #[test]
    fn test_unknown_ids_not_found() {
        let store = EmbeddedRecipeStore::global();
        let unknown = "00000000-0000-0000-0000-000000000000";
        assert!(!store.exists(unknown));
        assert!(store.get_by_id(unknown).is_err());
        assert!(store.get_by_uuid(&Uuid::nil()).is_err());
        assert!(!store.exists("day-0"));
        assert!(!store.exists("not-a-recipe"));
    }

    #[test]
    fn test_duplicate_uuid_or_id_rejected() {
        let mut store = EmbeddedRecipeStore {
            recipes: HashMap::new(),
            ids: HashMap::new(),
        };
        let recipe = EmbeddedRecipeStore::global().get_by_id("day-1").unwrap();
        store.insert(recipe.clone()).unwrap();

        let mut same_uuid = recipe.clone();
        same_uuid.id = "day-999".to_string();
        assert!(store.insert(same_uuid).is_err());

        let mut same_id = recipe;
        same_id.uuid = Uuid::nil();
        assert!(store.insert(same_id).is_err());
        assert_eq!(store.recipes.len(), 1);
    }

    #[test]
    fn test_global_instance_is_singleton() {
        let store1 = EmbeddedRecipeStore::global();
        let store2 = EmbeddedRecipeStore::global();

        // Both should point to the same instance
        assert_eq!(
            store1 as *const _, store2 as *const _,
            "Global instance should be a singleton"
        );
    }
}

/// Embedded plan store that includes all plan markdown files at compile time.
/// This is suitable for WASM/web targets where filesystem access is not available.
#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
pub struct EmbeddedPlanStore {
    plans: HashMap<u32, Plan>,
}

static EMBEDDED_PLAN_STORE: OnceLock<EmbeddedPlanStore> = OnceLock::new();

#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
impl EmbeddedPlanStore {
    /// Get the global embedded plan store instance
    pub fn global() -> &'static EmbeddedPlanStore {
        EMBEDDED_PLAN_STORE.get_or_init(|| {
            let mut store = EmbeddedPlanStore {
                plans: HashMap::new(),
            };
            store.load_embedded_plans();
            store
        })
    }

    /// Load all embedded plans at initialization
    fn load_embedded_plans(&mut self) {
        // Plan files are auto-generated by build.rs at compile time
        let plan_files: Vec<(u32, &str)> = include!(concat!(env!("OUT_DIR"), "/embedded_plans.rs"));

        for (week, content) in plan_files {
            match Self::parse_plan_markdown(content, week) {
                Ok(plan) => {
                    self.plans.insert(plan.week, plan);
                }
                Err(e) => {
                    // Log parsing failures to help with debugging
                    tracing::warn!(
                        week = week,
                        error = %e,
                        "Failed to parse plan markdown for week {}",
                        week
                    );
                }
            }
        }

        // Every week-N.md file is include_str!'d, so a missing file fails the build;
        // a shortfall here can only come from a parse failure, logged above.
        if !(52..=53).contains(&self.plans.len()) {
            tracing::error!(
                loaded = self.plans.len(),
                "Expected to load 52-53 plans but loaded {}",
                self.plans.len()
            );
        }
    }

    /// Parses plan data from markdown content
    fn parse_plan_markdown(content: &str, week: u32) -> PlanResult<Plan> {
        crate::parse::plan(content, week)
    }
}

#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
impl PlanReader for EmbeddedPlanStore {
    fn get_by_week(&self, week: u32) -> PlanResult<Plan> {
        self.plans
            .get(&week)
            .cloned()
            .ok_or_else(|| PlanError::NotFound(format!("Plan for week {} not found", week)))
    }

    fn get_all(&self) -> PlanResult<Vec<Plan>> {
        let mut plans: Vec<Plan> = self.plans.values().cloned().collect();
        // Sort by week number for consistent ordering
        plans.sort_by_key(|p| p.week);
        Ok(plans)
    }

    fn exists(&self, week: u32) -> bool {
        self.plans.contains_key(&week)
    }
}

#[cfg(test)]
mod plan_tests {
    use super::*;

    #[test]
    fn test_embedded_plan_store_loads_plans() {
        let store = EmbeddedPlanStore::global();
        let plans = store.get_all().unwrap();
        // 2024 has 52 ISO weeks, not 53 (week 53 file has incomplete data)
        assert!(
            plans.len() >= 52,
            "Should load at least 52 plans, got {}",
            plans.len()
        );
    }

    #[test]
    fn test_get_by_week() {
        let store = EmbeddedPlanStore::global();
        let recipe_store = EmbeddedRecipeStore::global();

        // Test week 1
        let plan = store.get_by_week(1).unwrap();
        assert_eq!(plan.week, 1);
        assert_eq!(plan.recipe_uuids.len(), 7);

        // Verify UUIDs match recipes for days 1-7
        for (i, day) in (1..=7).enumerate() {
            let day_id = format!("day-{}", day);
            let recipe = recipe_store.get_by_id(&day_id).unwrap();
            assert_eq!(plan.recipe_uuids[i], recipe.uuid);
        }

        // Test week 2
        let plan = store.get_by_week(2).unwrap();
        assert_eq!(plan.week, 2);
        assert_eq!(plan.recipe_uuids.len(), 7);

        // Verify UUIDs match recipes for days 8-14
        for (i, day) in (8..=14).enumerate() {
            let day_id = format!("day-{}", day);
            let recipe = recipe_store.get_by_id(&day_id).unwrap();
            assert_eq!(plan.recipe_uuids[i], recipe.uuid);
        }

        // Test last valid week (52 for 2024)
        let plan = store.get_by_week(52).unwrap();
        assert_eq!(plan.week, 52);
        assert_eq!(plan.recipe_uuids.len(), 7);
    }

    #[test]
    fn test_invalid_week() {
        let store = EmbeddedPlanStore::global();

        // Week 0 should fail
        assert!(store.get_by_week(0).is_err());

        // Week 54 should fail
        assert!(store.get_by_week(54).is_err());
    }

    #[test]
    fn test_plan_exists() {
        let store = EmbeddedPlanStore::global();

        // All weeks 1-52 should exist (2024 only has 52 weeks)
        for week in 1..=52 {
            assert!(store.exists(week), "Plan for week {} should exist", week);
        }

        // Week 0 and 54 should not exist
        assert!(!store.exists(0));
        assert!(!store.exists(54));
    }

    #[test]
    fn test_get_all_returns_sorted() {
        let store = EmbeddedPlanStore::global();
        let plans = store.get_all().unwrap();

        // Verify plans are sorted by week number
        for i in 0..plans.len() - 1 {
            assert!(
                plans[i].week < plans[i + 1].week,
                "Plans should be sorted by week number"
            );
        }
    }

    #[test]
    fn test_global_plan_instance_is_singleton() {
        let store1 = EmbeddedPlanStore::global();
        let store2 = EmbeddedPlanStore::global();

        // Both should point to the same instance
        assert_eq!(
            store1 as *const _, store2 as *const _,
            "Global instance should be a singleton"
        );
    }

    #[test]
    fn test_parse_plan_markdown() {
        let content = r#"# Week 1 Plan

Meal plan for ISO 8601 week 1.

Week: 1
Year: 2024
Days: 1, 2, 3, 4, 5, 6, 7
Recipe UUIDs: 9811d359-25fb-4cff-baf1-c78cd3243033, 4a604773-ec4d-47b1-b622-486bf61a878a, 8e3d2386-41ec-4471-9c09-7e794b0dc207, 6a25a017-327c-4c6d-aa91-b7c7268a7f1d, 12f50181-4156-4bee-b72a-7d7e10f19d2f, 8ffb2050-fa21-4827-b5be-664ee1af49d2, 2c14da93-84fd-4044-abf4-8dd83babec4c

## Recipe Days

This week's meal plan uses the following day-of-year recipes (Monday through Sunday):

- Monday: Day 1
- Tuesday: Day 2
- Wednesday: Day 3
"#;

        let plan = EmbeddedPlanStore::parse_plan_markdown(content, 1).unwrap();
        let recipe_store = EmbeddedRecipeStore::global();

        assert_eq!(plan.week, 1);
        assert_eq!(plan.recipe_uuids.len(), 7);

        // Verify UUIDs match the recipes for days 1-7
        for (i, day) in (1..=7).enumerate() {
            let day_id = format!("day-{}", day);
            let recipe = recipe_store.get_by_id(&day_id).unwrap();
            assert_eq!(plan.recipe_uuids[i], recipe.uuid);
        }
    }
}
