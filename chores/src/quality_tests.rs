#[test]
fn compare_splits_rises_and_falls() {
    let c = compare(
        &map(&[("clippy::a", 3), ("clippy::b", 2), ("clippy::gone", 1)]),
        &map(&[("clippy::a", 4), ("clippy::b", 2), ("clippy::new", 1)]),
    );
    assert_eq!(
        c.rose,
        vec![
            Change {
                lint: "clippy::a".into(),
                before: 3,
                after: 4
            },
            Change {
                lint: "clippy::new".into(),
                before: 0,
                after: 1
            },
        ]
    );
    assert_eq!(
        c.fell,
        vec![Change {
            lint: "clippy::gone".into(),
            before: 1,
            after: 0
        }]
    );
}

