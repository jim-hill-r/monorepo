#[test]
fn new_findings_prefer_changed_files() {
    let f = findings();
    let c = compare(&map(&[("clippy::format_push_string", 1)]), &count(&f));
    // doc_markdown, too_many_lines and dead_code rose from 0 too.
    let changed: BTreeSet<String> = ["demo/src/report.rs".to_string()].into();
    let named = new_findings(&c, &f, &changed);
    assert!(named.iter().all(|x| x.file == "demo/src/report.rs"));
    assert_eq!(named.len(), 2);
    let all = new_findings(&c, &f, &BTreeSet::new());
    assert_eq!(all.len(), 5);
}

