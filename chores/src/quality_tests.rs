use super::*;

const FIXTURE: &str = include_str!("../tests/fixtures/clippy-strict.jsonl");

fn findings() -> Vec<Finding> {
    parse_clippy_json(FIXTURE, "demo").expect("fixture parses")
}

fn map(pairs: &[(&str, u64)]) -> BTreeMap<String, u64> {
    pairs.iter().map(|(l, n)| ((*l).to_string(), *n)).collect()
}

#[test]
fn parses_warnings_with_a_lint_code_once_each() {
    let f = findings();
    let counts = count(&f);
    assert_eq!(
        counts,
        map(&[
            ("clippy::doc_markdown", 1),
            ("clippy::format_push_string", 2),
            ("clippy::too_many_lines", 1),
            ("dead_code", 1),
        ])
    );
}

#[test]
fn paths_are_repo_relative_and_use_the_primary_span() {
    let f = findings();
    let doc = f
        .iter()
        .find(|x| x.lint == "clippy::doc_markdown")
        .expect("doc_markdown finding");
    assert_eq!(doc.file, "demo/core/src/model.rs");
    assert_eq!((doc.line, doc.column), (3, 10));
    assert_eq!(
        doc.render(),
        "demo/core/src/model.rs:3:10: clippy::doc_markdown: item in documentation is missing backticks"
    );
}

#[test]
fn skips_registry_crates_summaries_and_notes() {
    let f = findings();
    assert!(f.iter().all(|x| !x.file.contains(".cargo")));
    assert!(f.iter().all(|x| x.lint != "clippy::needless_return"));
    assert_eq!(f.len(), 5);
}

#[test]
fn bad_json_is_an_error_naming_the_line() {
    let err = parse_clippy_json("{not json", "demo").expect_err("bad json");
    assert!(format!("{err:#}").contains("line 1"));
}

#[test]
fn non_json_lines_are_ignored() {
    let f = parse_clippy_json("   Compiling demo v0.1.0\n", "demo").expect("parses");
    assert!(f.is_empty());
}

#[test]
fn generated_code_is_left_out() {
    let line = FIXTURE
        .lines()
        .find(|l| l.contains("dead_code"))
        .expect("dead_code line");
    let f = parse_clippy_json(line, "infra").expect("parses");
    assert_eq!(f.len(), 1, "infra/src/report.rs is not generated");
    let line = line.replace("src/report.rs", "src/tfschema/cloudflare.rs");
    assert!(
        parse_clippy_json(&line, "infra")
            .expect("parses")
            .is_empty()
    );
}

#[test]
fn root_prefix_keeps_paths_as_they_are() {
    let f = parse_clippy_json(FIXTURE, ".").expect("parses");
    assert!(f.iter().any(|x| x.file == "src/lib.rs"));
}

#[test]
fn files_over_800_lines_are_findings() {
    let long = "x\n".repeat(801);
    let exact = "x\n".repeat(800);
    let generated = format!("// @generated by terrars\n{long}");
    let files = vec![
        ("a/src/long.rs".to_string(), long.clone()),
        ("a/src/exact.rs".to_string(), exact),
        ("a/src/gen.rs".to_string(), generated),
        ("infra/src/tfschema/big.rs".to_string(), long),
    ];
    let f = file_length_findings(&files);
    assert_eq!(f.len(), 1);
    assert_eq!(f[0].lint, FILE_TOO_LONG);
    assert_eq!(f[0].file, "a/src/long.rs");
    assert!(f[0].message.starts_with("801 lines"));
}

#[test]
fn baseline_round_trips() {
    let b = Baseline {
        updated: "2026-11-28".to_string(),
        lints: map(&[
            ("clippy::too_many_lines", 8),
            ("jimhillr::file_too_long", 1),
        ]),
    };
    let text = b.render();
    assert!(text.contains("total = 9\n"));
    assert!(text.contains("\"clippy::too_many_lines\" = 8\n"));
    assert_eq!(Baseline::parse(&text).expect("parses"), b);
}

#[test]
fn baseline_matches_the_plans_example() {
    let text = "[baseline]\nupdated = 2026-11-27\ntotal = 118\n\n[baseline.lints]\n\
                \"clippy::format_push_string\" = 30\n\"clippy::too_many_lines\" = 8\n";
    let b = Baseline::parse(text).expect("parses");
    assert_eq!(b.updated, "2026-11-27");
    assert_eq!(b.lints.get("clippy::format_push_string"), Some(&30));
}

