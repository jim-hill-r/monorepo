//! `cost render`: the limit tables in `standards/docs/free-tiers.md`.

use std::fs;
use std::path::Path;
use std::process::ExitCode;

use anyhow::{Context, Result, anyhow, bail};
use cost_model::{parse_limits, render_limits};

use crate::check::LIMITS;

pub const PAGE: &str = "standards/docs/free-tiers.md";
pub const START: &str = "<!-- limits:start (generated by `cost render` from standards/radar/limits.toml; edit that file instead) -->";
pub const END: &str = "<!-- limits:end -->";

/// The page with the generated part replaced.
pub fn rendered(page: &str, tables: &str) -> Result<String> {
    let start = page
        .find(START)
        .ok_or_else(|| anyhow!("{PAGE} has no `{START}` line"))?;
    let end = page
        .find(END)
        .ok_or_else(|| anyhow!("{PAGE} has no `{END}` line"))?;
    if end < start {
        bail!("{PAGE}: `{END}` comes before the start line");
    }
    Ok(format!(
        "{}{START}\n\n{tables}{}",
        &page[..start],
        &page[end..]
    ))
}

pub fn render(root: &Path, check: bool) -> Result<ExitCode> {
    let limits_text =
        fs::read_to_string(root.join(LIMITS)).with_context(|| format!("reading {LIMITS}"))?;
    let limits = parse_limits(&limits_text).map_err(|e| anyhow!("{LIMITS}: {e}"))?;
    let page = fs::read_to_string(root.join(PAGE)).with_context(|| format!("reading {PAGE}"))?;
    let new = rendered(&page, &render_limits(&limits))?;
    if new == page {
        println!("cost render: {PAGE} is up to date");
        return Ok(ExitCode::SUCCESS);
    }
    if check {
        println!(
            "error[COST-RENDER] {PAGE} does not match {LIMITS}; run `mise run fix` in standards"
        );
        return Ok(ExitCode::FAILURE);
    }
    fs::write(root.join(PAGE), new).with_context(|| format!("writing {PAGE}"))?;
    println!("cost render: rewrote the limit tables in {PAGE}");
    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_replaces_only_the_generated_part() {
        let page = format!("# Free tiers\n\n{START}\n\nold\n{END}\n\nafter\n");
        let out = rendered(&page, "new\n").expect("renders");
        assert_eq!(
            out,
            format!("# Free tiers\n\n{START}\n\nnew\n{END}\n\nafter\n")
        );
        assert_eq!(rendered(&out, "new\n").expect("again"), out);
    }

    #[test]
    fn test_needs_both_markers() {
        assert!(rendered("no markers", "x").is_err());
        assert!(rendered(&format!("{END}\n{START}\n"), "x").is_err());
    }
}
