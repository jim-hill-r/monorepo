#!/usr/bin/env bash
# Tech radar: check standards/radar/radar.json and render its tables into
# standards/docs/tech-radar.md (between the radar:start and radar:end lines).
#
#   radar.sh check    Validate the data and fail if the page is out of date.
#   radar.sh render   Rewrite the generated part of the page.
#
#   RAD-001  radar.json is a JSON array.
#   RAD-002  Every blip has name, ring, quadrant, isNew, kind, description,
#            exemplars, sources, claude and budget, with the right types and
#            allowed values.
#   RAD-003  Blip names are unique.
#   RAD-004  Every exemplar and every repo-relative source path exists.
#   RAD-005  Every Assess blip has at least one source (its evaluation).
#   RAD-006  The tables in tech-radar.md match radar.json.
#   RAD-007  Every vendor says how its billing is checked (Jim, 2026-11-27:
#            "the billing check should check every vendor in the tech
#            radar"): `billing` has `api` (names standards/scripts/
#            billing-check.sh checks), `human` (a settings.toml id Jim
#            checks, or "") and a `note`. An Adopt or Trial vendor needs at
#            least one of api and human.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
data="$root/standards/radar/radar.json"
page="$root/standards/docs/tech-radar.md"
settings="$root/standards/settings.toml"
billing_check="$root/standards/scripts/billing-check.sh"
start='<!-- radar:start (generated by standards/scripts/radar.sh render; edit radar.json instead) -->'
end='<!-- radar:end -->'

errors=0
err() { echo "error[$1]: $2" >&2; errors=$((errors + 1)); }

# Markdown tables, one per quadrant, rings in order. Links are relative to
# standards/docs/.
tables() {
  jq -r '
    def link: if test("^https?://") then
        (if test("/pull/[0-9]+$") then "[PR \(capture("/pull/(?<n>[0-9]+)$").n)](\(.))" else "[link](\(.))" end)
      else "[\(split("/") | last)](../../\(.))" end;
    def cell: gsub("\\|"; "\\|");
    ["Adopt", "Trial", "Assess", "Hold"] as $rings
    | "Total budget: **$\([.[].budget] | add) a month** (\([.[] | select(.budget > 0) | "\(.name) $\(.budget)"] | join(", "))). Everything else is $0: free plans and open source.\n",
      (["Techniques", "Tools", "Platforms", "Languages & Frameworks"][] as $q
    | "### \($q)\n",
      "| Blip | Ring | Kind | Budget a month | Exemplar projects | Why | Claude support | Sources |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |",
      ([.[] | select(.quadrant == $q)]
        | sort_by((.ring as $r | $rings | index($r)), (.name | ascii_downcase))[]
        | "| \(.name | cell)\(if .isNew == "TRUE" then " (new)" else "" end) | \(.ring) | \(.kind) | $\(.budget) | \(
            if (.exemplars | length) == 0 then "none yet"
            else [.exemplars[] | "[\(.)](../../\(.))"] | join(", ") end) | \(.description | cell) | \(
            if .claude == "" then "-" else (.claude | cell) end) | \(
            [.sources[] | link] | join(", ")) |"),
      ""),
      "### Billing checks\n",
      "How the billing of each vendor is checked: weekly by [billing-check.sh](../scripts/billing-check.sh) through a read-only API, or by Jim through a [settings check](../settings.toml). See [Billing checks](free-tiers.md#billing-checks).\n",
      "| Vendor | Ring | Read-only API check | Jim checks | Why |",
      "| --- | --- | --- | --- | --- |",
      ([.[] | select(.kind == "vendor")]
        | sort_by((.ring as $r | $rings | index($r)), (.name | ascii_downcase))[]
        | "| \(.name | cell) | \(.ring) | \(if (.billing.api // []) == [] then "-" else (.billing.api | join(", ")) end) | \(
            if (.billing.human // "") == "" then "-" else "`\(.billing.human)`" end) | \(.billing.note // "" | cell) |"),
      ""
  ' "$data"
}

check() {
  jq -e 'type == "array"' "$data" >/dev/null 2>&1 || { err RAD-001 "$data is not a JSON array"; return; }

  while IFS= read -r line; do err RAD-002 "$line"; done < <(jq -r '
    .[] | . as $b | (.name // "<no name>") as $n
    | (if (.name | type) != "string" or .name == "" then "\($n): name must be a non-empty string" else empty end),
      (if ([.ring] | inside(["Adopt", "Trial", "Assess", "Hold"])) | not then "\($n): ring must be Adopt, Trial, Assess or Hold" else empty end),
      (if ([.quadrant] | inside(["Techniques", "Tools", "Platforms", "Languages & Frameworks"])) | not then "\($n): quadrant must be Techniques, Tools, Platforms or Languages & Frameworks" else empty end),
      (if ([.isNew] | inside(["TRUE", "FALSE"])) | not then "\($n): isNew must be \"TRUE\" or \"FALSE\"" else empty end),
      (if ([.kind] | inside(["technology", "vendor"])) | not then "\($n): kind must be technology or vendor" else empty end),
      (if (.description | type) != "string" or .description == "" then "\($n): description must be a non-empty string" else empty end),
      (if (.exemplars | type) != "array" then "\($n): exemplars must be an array" else empty end),
      (if (.sources | type) != "array" then "\($n): sources must be an array" else empty end),
      (if (.budget | type) != "number" or .budget < 0 then "\($n): budget must be a number of US dollars a month, 0 or more" else empty end),
      (if (.claude | type) != "string" then "\($n): claude must be a string (empty when Claude has no plugin or MCP server for it)" else empty end)
  ' "$data")

  while IFS= read -r n; do err RAD-003 "duplicate blip name: $n"; done < <(jq -r '[.[].name] | group_by(.)[] | select(length > 1)[0]' "$data")

  while IFS=$'\t' read -r n p; do
    [ -e "$root/$p" ] || err RAD-004 "$n: $p does not exist"
  done < <(jq -r '.[] | .name as $n | ((.exemplars // [])[], ((.sources // [])[] | select(test("^https?://") | not))) | "\($n)\t\(.)"' "$data")

  local apis ids
  apis=$(bash "$billing_check" vendors)
  ids=$(sed -n 's/^id = "\(.*\)"$/\1/p' "$settings")
  while IFS= read -r line; do err RAD-007 "$line"; done < <(jq -r --arg apis "$apis" --arg ids "$ids" '
    ($apis | split(" ")) as $known | ($ids | split("\n")) as $ids
    | .[] | select(.kind == "vendor") | .name as $n | .billing as $b
    | if ($b | type) != "object" then "\($n): a vendor needs billing {api, human, note}: how its billing is checked"
      else
        (if ($b.api | type) != "array" then "\($n): billing.api must be an array" else
          ($b.api[] | select(. as $a | $known | index($a) | not) | "\($n): billing.api \(.) is not a vendor billing-check.sh checks (\($known | join(", ")))") end),
        (if ($b.human | type) != "string" then "\($n): billing.human must be a string" 
         elif $b.human != "" and ($ids | index($b.human) | not) then "\($n): billing.human \($b.human) is not a setting id in standards/settings.toml" else empty end),
        (if ($b.note | type) != "string" or $b.note == "" then "\($n): billing.note must say why it is checked this way" else empty end),
        (if (.ring == "Adopt" or .ring == "Trial") and (($b.api // []) | length) == 0 and ($b.human // "") == ""
         then "\($n): an \(.ring) vendor needs a billing check: an api billing-check.sh runs, or a human settings check" else empty end)
      end
  ' "$data")

  while IFS= read -r n; do err RAD-005 "$n: an Assess blip needs a source for its evaluation"; done < <(jq -r '.[] | select(.ring == "Assess" and ((.sources // []) | length) == 0) | .name' "$data")

  [ "$errors" -eq 0 ] || return 0
  local out
  out="$(rendered)" || { err RAD-006 "could not render the radar tables"; return 0; }
  if ! diff -q <(printf '%s\n' "$out") "$page" >/dev/null; then
    err RAD-006 "standards/docs/tech-radar.md is out of date: run 'bash standards/scripts/radar.sh render'"
  fi
}

# The page with its generated part replaced.
rendered() {
  grep -qxF "$start" "$page" && grep -qxF "$end" "$page" || { echo "missing radar markers in $page" >&2; return 1; }
  local body
  body="$(tables)" || return 1
  awk -v s="$start" -v e="$end" -v body="$body" '
    $0 == s { print; print ""; print body; print ""; skip = 1; next }
    $0 == e { skip = 0 }
    !skip { print }
  ' "$page"
}

case "${1:-check}" in
  check)
    check
    [ "$errors" -eq 0 ] || { echo "radar: $errors error(s)" >&2; exit 1; }
    echo "radar: ok ($(jq length "$data") blips)"
    ;;
  render)
    out="$(rendered)"
    printf '%s\n' "$out" > "$page"
    echo "radar: rendered $(jq length "$data") blips into standards/docs/tech-radar.md"
    ;;
  *)
    echo "usage: radar.sh [check|render]" >&2
    exit 2
    ;;
esac
